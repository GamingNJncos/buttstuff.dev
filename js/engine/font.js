const FONTS = { f5: { w: 5, h: 7, adv: 6 }, f3: { w: 3, h: 5, adv: 4 } };

export function textWidth(s, font = 'f5') {
  const n = [...s].length;
  return n ? n * FONTS[font].adv - 1 : 0;
}

export function drawText(ctx, s, x, y, color, font = 'f5') {
  ctx.fillStyle = color;
  const { w, adv } = FONTS[font];
  let i = 0;
  for (const raw of s) {
    if (font === 'f3') {
      const g = FONT3[raw.toUpperCase()] ?? FONT3['?'];
      for (let b = 0; b < 15; b++) {
        if (g.charCodeAt(b) === 49) ctx.fillRect(x + i * adv + (b % 3), y + ((b / 3) | 0), 1, 1);
      }
    } else {
      const g = FONT5[raw] ?? FONT5[raw.toUpperCase()] ?? FONT5['?'];
      for (let r = 0; r < 7; r++) {
        for (let c = 0; c < w; c++) {
          if (g[r].charCodeAt(c) === 49) ctx.fillRect(x + i * adv + c, y + r, 1, 1);
        }
      }
    }
    i++;
  }
}

export function drawTextShadow(ctx, s, x, y, color, shadow, font = 'f5') {
  drawText(ctx, s, x + 1, y + 1, shadow, font);
  drawText(ctx, s, x, y, color, font);
}

// Embossed: dark copy offset +1,+1 under the light copy.
export function drawStencil(ctx, s, x, y, light, dark, font = 'f5') {
  drawText(ctx, s, x + 1, y + 1, dark, font);
  drawText(ctx, s, x, y, light, font);
}
